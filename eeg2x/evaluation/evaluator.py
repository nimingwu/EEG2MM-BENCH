def _matches(fname: str, patterns: List[str]) -> bool:
    """Filename match against registry h5_patterns (shared helper)."""
    return any(fnmatch.fnmatch(fname, pat) for pat in patterns)


def extract_ground_truths(h5_files: List[Dict[str, str]],
                          task: str) -> Tuple[Dict[str, Any], Dict[str, Dict[str, str]]]:
    """Build sample_id → ground_truth and sample_id → meta for all samples.

    Returns
    -------
    gts  : {sample_id: gt_label}
    meta : {sample_id: {"dataset": ..., "subject": ...}} — the ONLY authority
           for dataset/subject attribution (no string-substring matching).

    Filename matching and GT field names come from TASK_REGISTRY
    (h5_patterns / gt_field) — the registry is the declaration
    (principle 3: single source of truth).
    """
    task_cfg = get_task_config(task)
    patterns = task_cfg["h5_patterns"]
    gts: Dict[str, Any] = {}
    meta: Dict[str, Dict[str, str]] = {}

    def _record(sid: str, gt: Any, info: Dict[str, str],
                extra: Dict[str, Any] | None = None):
        gts[sid] = gt
        meta[sid] = {"dataset": str(info["dataset"]),
                     "subject": str(info["subject_id"])}
        if extra:
            meta[sid].update(extra)

    # ---- Image tasks (batch read h5, avoid per-row file open) ----
    if task in ("image_retrieval", "image_generation", "concept_classification"):
        for info in h5_files:
            if not _matches(info["filename"], patterns):
                continue
            h5_path = info["path"]
            n_epochs = info["n_epochs"]
            file_stem = Path(h5_path).stem
            try:
                with h5py.File(h5_path, "r") as h5:
                    labels = h5["event_label"][:]
                    stim_nums = []
                    if "event_stim_number" in h5:
                        stim_nums = h5["event_stim_number"][:]

                    for i in range(n_epochs):
                        label_bytes = labels[i]
                        concept_name = label_bytes.decode("utf-8") if isinstance(label_bytes, bytes) else str(label_bytes)
                        sid = f"{file_stem}_trial-{i:06d}"

                        if task in ("image_retrieval", "concept_classification"):
                            gt = concept_name
                        elif task == "image_generation":
                            if "stimulus_uri" in h5:
                                raw_uri = h5["stimulus_uri"][i]
                                gt = raw_uri.decode("utf-8") if isinstance(raw_uri, bytes) else str(raw_uri)
                            elif "event_image_file" in h5:
                                raw_uri = h5["event_image_file"][i]
                                gt = raw_uri.decode("utf-8") if isinstance(raw_uri, bytes) else str(raw_uri)
                            else:
                                gt = ""
                        _record(sid, gt, info)
            except Exception as exc:
                logging.getLogger("benchmark_eval").warning(f"Failed reading {h5_path}: {exc}")
                continue

    # ---- Text tasks (read h5 directly, field name from registry gt_field) ----
    elif task in ("word_decoding", "sentence_generation"):
        gt_field = task_cfg["gt_field"]
        for info in h5_files:
            if not _matches(info["filename"], patterns):
                continue
            fname = Path(info["path"]).stem
            with h5py.File(info["path"], "r") as h5:
                if gt_field not in h5:
                    continue
                # target_texts_json 存同一刺激句的八个改写/简化变体。SemKey 的
                # MTV 协议 BLEU 按完整参考集打分；没有这一列的旧文件保持单参考。
                has_variants = (task == "sentence_generation"
                                and "target_texts_json" in h5)
                for i in range(info["n_epochs"]):
                    b = h5[gt_field][i]
                    text = b.decode() if isinstance(b, bytes) else str(b)
                    if task == "word_decoding":
                        sid = f"{fname}_word-{i:04d}"
                    else:
                        sid = f"{fname}_sent-{i:04d}"
                    extra = None
                    if has_variants:
                        v = h5["target_texts_json"][i]
                        v = v.decode() if isinstance(v, bytes) else str(v)
                        try:
                            refs = json.loads(v)
                        except (TypeError, ValueError):
                            refs = None
                        if isinstance(refs, list):
                            extra = {"target_texts": [str(r) for r in refs]}
                    _record(sid, text, info, extra=extra)

    # ---- Speech retrieval (Brennan2019 word-level) ----
    # GT = 词实例 id（word_order，registry gt_field）——实例级匹配，
    # 与候选池 id（candidate_pool_ids.txt 的 word_order 行）类型一致。
    # 同时附带 word_text 到 meta，供词类型聚合指标使用
    # （对齐 NeuralBench full-retrieval 的 instance-agg / subject-agg 指标）。
    elif task == "speech_retrieval":
        gt_field = task_cfg["gt_field"]
        for info in h5_files:
            if not _matches(info["filename"], patterns):
                continue
            fname = Path(info["path"]).stem
            with h5py.File(info["path"], "r") as h5:
                if gt_field not in h5:
                    continue
                has_word_text = "word_text" in h5
                for i in range(info["n_epochs"]):
                    v = h5[gt_field][i]
                    if isinstance(v, (int, np.integer, np.floating)):
                        gt = str(int(v))
                    elif isinstance(v, bytes):
                        gt = v.decode("utf-8")
                    else:
                        gt = str(v)
                    sid = f"{fname}_word-{i:04d}"
                    extra = dict(info)
                    if has_word_text:
                        wt = h5["word_text"][i]
                        extra["word_text"] = (
                            wt.decode("utf-8") if isinstance(wt, bytes)
                            else str(wt)
                        )
                    _record(sid, gt, extra)

    # ---- Video generation (SEED-DV / Smit2025 / EMD) ----
    # 真值 = 测试 H5 里的 gt_frames；交给指标的是
    # h5://<file>#gt_frames[<row>] 引用，metrics/video_generation.py 直接切片，
    # 不再解码源视频。训练集没有这一列，遇到就跳过而不是伪造。
    elif task == "video_generation":
        gt_field = task_cfg["gt_field"]
        for info in h5_files:
            if not _matches(info["filename"], patterns):
                continue
            h5_path = info["path"]
            fname = Path(h5_path).stem
            with h5py.File(h5_path, "r") as h5:
                if gt_field not in h5:
                    continue
                if h5[gt_field].shape[0] != info["n_epochs"]:
                    raise ValueError(
                        f"{h5_path}: gt_frames has {h5[gt_field].shape[0]} rows "
                        f"but the file declares {info['n_epochs']} epochs")
                for i in range(info["n_epochs"]):
                    _record(f"{fname}_clip-{i:04d}",
                            f"h5://{h5_path}#gt_frames[{i}]", info)

    # ---- Registered but not wired yet (principle 3/7: fail visible) ----
    elif task in ("speech_reconstruction", "speech_detection"):
        raise NotImplementedError(
            f"Task '{task}' is registered but has no ground-truth extraction "
            "branch in benchmark_eval yet. Per principles 3 & 7 (registered = "
            "evaluable; no silent failures), evaluation is refused until the "
            "branch is implemented."
        )

    else:
        raise NotImplementedError(
            f"Task '{task}' has no ground-truth extraction branch."
        )

    return gts, meta


