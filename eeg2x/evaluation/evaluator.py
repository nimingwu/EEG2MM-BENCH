def generate_report(task: str,
                    ground_truths: Dict[str, Any],
                    predictions: Dict[str, Any],
                    h5_files: List[Dict[str, str]],
                    metric_names: List[str] = None,
                    candidate_pool_ids: list = None,
                    candidate_embeddings: list = None,
                    sample_meta: Dict[str, Dict[str, str]] = None) -> Dict[str, Any]:
    """Compute metrics per dataset and overall.

    Parameters
    ----------
    task : str
    ground_truths : {sample_id: gt_label}
    predictions : {sample_id: model_output_dict}
    h5_files : list of h5 file info
    metric_names : list of metric names, None = all applicable
    candidate_pool_ids : candidate list for ranked predictions
    sample_meta : {sample_id: {"dataset", "subject"}} from
        extract_ground_truths — the single authority for attribution
        (principle 3/6; no string-substring matching)

    Returns
    -------
    report dict with structure described at the top of this file.
    """
    # ---- Validate predictions (principle 4: machine-checkable) ----
    pred_required = get_task_config(task).get("pred_required", [])
    invalid_preds: Dict[str, Any] = {}
    if pred_required:
        valid = {}
        for sid, pred in predictions.items():
            # any-of: 满足任一必需键即视为合法（如 image_generation 的
            # path / data_ref 二选一）
            if isinstance(pred, dict) and any(k in pred for k in pred_required):
                valid[sid] = pred
            else:
                invalid_preds[sid] = pred
        if invalid_preds:
            log.warning(
                f"{len(invalid_preds)} prediction(s) missing required keys "
                f"{pred_required} — excluded from scoring (principle 4)"
            )
        predictions = valid
    if not predictions:
        raise ValueError(
            f"No valid predictions for task '{task}' (required keys: "
            f"{pred_required}). Check sample_id / prediction format conventions."
        )

    # Organise samples by dataset (single authority: sample_meta)
    sample_to_dataset: Dict[str, str] = {}
    if sample_meta:
        sample_to_dataset = {sid: m["dataset"] for sid, m in sample_meta.items()}

    # Determine metric names
    if metric_names is None:
        metric_names = sorted(list_metrics(task).keys())
    else:
        available = list_metrics(task)
        for name in metric_names:
            if name not in available:
                log.warning(f"Metric '{name}' not applicable to task '{task}', skipping.")
        metric_names = [n for n in metric_names if n in available]

    if not metric_names:
        log.warning(f"No applicable metrics found for task '{task}'.")
        return {"task": task, "error": "no applicable metrics"}

    # Per-dataset scores
    datasets_scores: Dict[str, Dict] = {}
    dataset_samples: Dict[str, list] = defaultdict(list)
    for sid, gt in ground_truths.items():
        ds = sample_to_dataset.get(sid, "unknown")
        pred = predictions.get(sid)
        if pred is None:
            continue
        dataset_samples[ds].append((sid, pred, gt))

    # Extract prediction values with the right format for each task
    def extract_pred(pred_dict: Any, task_name: str) -> Any:
        """Normalise prediction dict to the format expected by metrics."""
        if isinstance(pred_dict, dict):
            if task_name in ("image_retrieval", "speech_retrieval"):
                ranked = pred_dict.get("ranked_indices", [])
                if candidate_pool_ids:
                    return [candidate_pool_ids[idx] for idx in ranked if idx < len(candidate_pool_ids)]
                return ranked
            elif task_name == "image_generation":
                return pred_dict.get("path", pred_dict.get("data_ref", ""))
            elif task_name == "video_generation":
                # path 指向 .npy 堆叠数组（路径带 #row）或整段文件；解析交给
                # metrics/video_generation.py。
                return pred_dict.get("path", pred_dict.get("data_ref", ""))
            elif task_name == "concept_classification":
                # Return [predicted_concept_name] as ranked list
                pred = pred_dict.get("predicted_concept", "")
                return [pred] if pred else []
            elif task_name in ("sentence_generation",):
                return pred_dict.get("generated_text", "")
            elif task_name in ("word_decoding",):
                return pred_dict.get("predicted_word", "")
        return pred_dict

    def _query_embeddings(samples: list) -> Optional[list]:
        """Extract query_embedding from prediction dicts (opt-in, speech_retrieval only)."""
        if task != "speech_retrieval":
            return None
        embs = []
        for sid, p, _ in samples:
            qe = p.get("query_embedding") if isinstance(p, dict) else None
            if qe is not None:
                embs.append(qe)
            else:
                return None  # 不全则有则退化为排名路径
        return embs

    def _subject_ids(samples: list) -> Optional[list]:
        """Subject per sample, from the single-authority sample_meta."""
        if task != "speech_retrieval" or not sample_meta:
            return None
        return [sample_meta.get(sid, {}).get("subject", "unknown")
                for sid, _, _ in samples]

    def _word_texts(samples: list) -> Optional[list]:
        """Word text per sample (only for speech_retrieval)."""
        if task != "speech_retrieval" or not sample_meta:
            return None
        return [sample_meta.get(sid, {}).get("word_text", "")
                for sid, _, _ in samples]

    def _mtv_references(samples: list) -> Optional[list]:
        """每个样本的改写参考集（仅 sentence_generation）。

        只有**所有**样本都带 target_texts 时才返回，否则返回 None：需要完整
        参考集的指标（MTV BLEU）会跳过，而不是用截断的参考集悄悄打分。
        """
        if task != "sentence_generation" or not sample_meta:
            return None
        refs = []
        for sid, _, _ in samples:
            r = sample_meta.get(sid, {}).get("target_texts")
            if not r:
                return None
            refs.append(list(r))
        return refs

    def _candidate_pool_word_texts() -> Optional[list]:
        """Map candidate_pool_ids (word_order strings) → word_text strings.

        Builds the mapping from the h5 test files by reading word_order →
        word_text pairs. Returns a list of word_text in the same order
        as candidate_pool_ids.
        """
        if task != "speech_retrieval" or not candidate_pool_ids:
            return None
        patterns = get_task_config(task)["h5_patterns"]
        # Build order→text map from all test h5 files
        order_to_text = {}
        for info in h5_files:
            if not _matches(info["filename"], patterns):
                continue
            try:
                with h5py.File(info["path"], "r") as h5:
                    if "word_order" not in h5 or "word_text" not in h5:
                        continue
                    for wo, wt in zip(h5["word_order"][:], h5["word_text"][:]):
                        wo_str = str(int(wo) if isinstance(
                            wo, (int, np.integer, np.floating)) else wo)
                        wt_str = (wt.decode("utf-8") if isinstance(wt, bytes)
                                 else str(wt))
                        order_to_text[wo_str] = wt_str
            except Exception:
                continue
        if not order_to_text:
            return None
        return [order_to_text.get(cid, str(cid))
                for cid in candidate_pool_ids]

    pool_size = len(candidate_pool_ids) if candidate_pool_ids else None
    cand_word_texts = _candidate_pool_word_texts()

    for ds, samples in dataset_samples.items():
        preds = [extract_pred(p, task) for _, p, _ in samples]
        gts_list = [gt for _, _, gt in samples]

        log.info(f"  Evaluating {ds}: {len(preds)} samples")
        eval_kwargs = {}
        subject_ids = _subject_ids(samples)
        if subject_ids is not None:
            eval_kwargs["subject_ids"] = subject_ids
        word_texts = _word_texts(samples)
        if word_texts is not None:
            eval_kwargs["word_texts"] = word_texts
        mtv_refs = _mtv_references(samples)
        if mtv_refs is not None:
            eval_kwargs["mtv_references"] = mtv_refs
        q_embs = _query_embeddings(samples)
        if q_embs is not None and candidate_embeddings is not None:
            eval_kwargs["query_embeddings"] = q_embs
            eval_kwargs["candidate_embeddings"] = candidate_embeddings
        if cand_word_texts is not None:
            eval_kwargs["candidate_pool_word_texts"] = cand_word_texts
        if pool_size:
            eval_kwargs["pool_size"] = pool_size
        scores = evaluate(
            task=task,
            predictions=preds,
            ground_truths=gts_list,
            metrics=metric_names,
            **eval_kwargs,
        )
        datasets_scores[ds] = {
            "n_samples": len(samples),
            "metrics": scores,
        }

    # Overall scores (across all datasets)
    all_preds = []
    all_gts = []
    all_sids = []
    for sid, gt in ground_truths.items():
        pred = predictions.get(sid)
        if pred is None:
            continue
        all_preds.append(extract_pred(pred, task))
        all_gts.append(gt)
        all_sids.append(sid)

    overall_scores = {}
    if all_preds:
        overall_kwargs = {}
        if task == "sentence_generation" and sample_meta:
            refs = [sample_meta.get(s, {}).get("target_texts") for s in all_sids]
            if all(refs):
                overall_kwargs["mtv_references"] = [list(r) for r in refs]
        if task == "speech_retrieval" and sample_meta:
            overall_kwargs["subject_ids"] = [
                sample_meta.get(s, {}).get("subject", "unknown")
                for s in all_sids
            ]
            overall_kwargs["word_texts"] = [
                sample_meta.get(s, {}).get("word_text", "")
                for s in all_sids
            ]
            # Extract query embeddings from all predictions
            all_q_embs = []
            for s in all_sids:
                p = predictions.get(s, {})
                qe = p.get("query_embedding") if isinstance(p, dict) else None
                if qe is not None:
                    all_q_embs.append(qe)
                else:
                    all_q_embs = None
                    break
            if all_q_embs is not None and candidate_embeddings is not None:
                overall_kwargs["query_embeddings"] = all_q_embs
                overall_kwargs["candidate_embeddings"] = candidate_embeddings
        if cand_word_texts is not None:
            overall_kwargs["candidate_pool_word_texts"] = cand_word_texts
        if pool_size:
            overall_kwargs["pool_size"] = pool_size
        overall_scores = evaluate(
            task=task,
            predictions=all_preds,
            ground_truths=all_gts,
            metrics=metric_names,
            **overall_kwargs,
        )

    # Build report
    matched = len([k for k in ground_truths if k in predictions])
    report = {
        "benchmark_version": "0.1.0",
        "generated_at": datetime.now().isoformat(),
        "task": task,
        "metrics_used": metric_names,
        "datasets": datasets_scores,
        "overall": overall_scores,
        "summary": {
            "total_samples_ground_truth": len(ground_truths),
            "total_samples_with_prediction": matched,
            "total_predictions": len(predictions) + len(invalid_preds),
            "total_invalid_predictions": len(invalid_preds),
            "total_matched_samples": matched,
            "total_unmatched_predictions": max(
                len(predictions) - matched, 0),
            "total_files": len(h5_files),
        },
    }

    # No matches is a hard failure (principle 3/7: fail visible)
    if matched == 0 and ground_truths:
        raise ValueError(
            f"0 of {len(ground_truths)} ground-truth samples matched by "
            "predictions. Check the sample_id convention (single authority: "
            "extract_ground_truths) — see readme_old.md sample_id table."
        )

    return report


def print_report(report: Dict[str, Any]):
    """Pretty-print the report to stdout."""
    task = report.get("task", "?")
    print(f"\n{'='*60}")
    print(f"Benchmark Report — Task: {task}")
    print(f"{'='*60}")
    print(f"  Version:    {report.get('benchmark_version', '?')}")
    print(f"  Generated:  {report.get('generated_at', '?')}")
    print(f"  Metrics:    {', '.join(report.get('metrics_used', []))}")
    summary = report.get("summary", {})
    print(f"  GT samples: {summary.get('total_samples_ground_truth', '?')}")
    print(f"  Predictions:{summary.get('total_samples_with_prediction', '?')}")

    for ds_name, ds_data in report.get("datasets", {}).items():
        print(f"\n  [{ds_name}]  ({ds_data.get('n_samples', 0)} samples)")
        for m_name, m_score in ds_data.get("metrics", {}).items():
            direction = ""
            if m_name in ("wer", "swav", "fid"):
                direction = "  ↓ (lower is better)"
            elif m_name in ("top1_accuracy", "top5_accuracy", "map",
                            "clip_similarity", "pixcorr", "ssim",
                            "alexnet_2", "alexnet_5", "inception",
                            "bleu_1", "bleu_4", "rouge_l", "meteor",
                            "bertscore"):
                direction = "  ↑ (higher is better)"
            if isinstance(m_score, float):
                print(f"    {m_name:20s} = {m_score:.4f}{direction}")
            else:
                print(f"    {m_name:20s} = {m_score}{direction}")

    overall = report.get("overall", {})
    if overall:
        print(f"\n  [Overall]")
        for m_name, m_score in overall.items():
            if isinstance(m_score, float):
                print(f"    {m_name:20s} = {m_score:.4f}")
            else:
                print(f"    {m_name:20s} = {m_score}")

    print(f"\n{'='*60}")


