def discover_h5_files(h5_dir: str,
                      task: str = None) -> List[Dict[str, str]]:
    """Scan h5_dir for h5 files, categorising by dataset and subject.

    Returns list of {path, dataset, subject_id, run_info}.
    Unreadable files are counted and logged — never silently dropped
    (principle 7: no silent failures).
    """
    h5_dir = Path(h5_dir)
    files = []
    skipped: List[str] = []

    for f in sorted(h5_dir.glob("*.h5")):
        if task is not None:
            try:
                if not _matches(f.name, get_task_config(task)["h5_patterns"]):
                    continue
            except (KeyError, TypeError):
                pass
        try:
            with h5py.File(f, "r") as h5:
                dataset = h5.attrs.get("dataset", "unknown")
                subj = h5.attrs.get("subject_id", f.stem)
                if "n_epochs" in h5.attrs:
                    n_epochs = h5.attrs["n_epochs"]
                else:
                    eeg_name = next((name for name in ("data", "eeg") if name in h5), None)
                    if eeg_name is None:
                        raise KeyError("missing root EEG dataset ('data' or 'eeg')")
                    n_epochs = h5[eeg_name].shape[0]
                epoch_type = h5.attrs.get("epoch_type", "trial")
        except Exception as exc:
            skipped.append(f"{f.name} ({exc})")
            continue

        files.append({
            "path": str(f),
            "dataset": str(dataset),
            "subject_id": str(subj),
            "n_epochs": int(n_epochs),
            "epoch_type": str(epoch_type),
            "filename": f.name,
        })

    if skipped:
        log.warning(f"Skipped {len(skipped)} unreadable h5 file(s): {skipped}")

    return files


def print_dataset_info(h5_dir: str):
    """Print a summary of all h5 files found (dry-run)."""
    files = discover_h5_files(h5_dir)
    if not files:
        log.warning(f"No h5 files found in {h5_dir}")
        return

    by_dataset = defaultdict(list)
    for f in files:
        by_dataset[f["dataset"]].append(f)

    print(f"\n{'='*60}")
    print(f"H5 files in: {h5_dir}")
    print(f"{'='*60}")

    for dataset, fs in sorted(by_dataset.items()):
        print(f"\n  Dataset: {dataset}")
        print(f"  {'-'*40}")
        n_subj = len(set(f["subject_id"] for f in fs))
        n_total_ep = sum(f["n_epochs"] for f in fs)
        print(f"    {len(fs)} files, {n_subj} subjects, {n_total_ep} total epochs")
        for f in fs:
            print(f"      {f['filename']:50s}  {f['n_epochs']:6d} epochs")


