"""
Benchmark Evaluation Script
============================
Reads standardized HDF5 data, accepts model predictions, and outputs
a structured evaluation report across all applicable metrics.

Workflow:
  1. Scan a directory for h5 files, organise by dataset and task
  2. Read ground-truth labels from h5 via the task interface
  3. Accept model predictions from a JSON file (sample_id → prediction)
  4. Compute all applicable metrics
  5. Print and save a structured report

Usage (without a model — prepare predictions manually):
  python benchmark_eval.py --h5_dir ./h5_output \\
                           --predictions ./my_preds.json \\
                           --task image_retrieval

Usage (dry-run — just list all samples and ground truths):
  python benchmark_eval.py --h5_dir ./h5_output --info

Prediction JSON format
-----------------------
Each key is a sample_id (as generated by the task interface's Sample.from_h5_row).
Each value depends on the task:

  image_retrieval:
    {"thingseeg_sub-01_trial-000042": {"ranked_indices": [0, 7, 3], "candidate_pool_ids": [...]}}

  image_generation:
    {"thingseeg_sub-01_trial-000042": {"data_ref": "h5://outputs/gen.h5#img_0042",
                                        "path": "/path/to/gen/image.jpg"}}

  concept_classification:
    {"thingseeg_sub-01_trial-000042": {"predicted_class": 275}}

  sentence_generation:
    {"roamm_sub-10014_sentence-0003": {"generated_text": "Pluto is a dwarf planet."}}

  word_decoding:
    {"speech_sub-001_word-0042": {"predicted_word": "man"}}

  speech_retrieval:
    {"brennan2019_S01_test_epoched_word-0003": {"ranked_indices": [0, 7, 3],
                                                "candidate_pool_ids": ["for", "cake", ...]}}

Output report format (JSON)
----------------------------
  {
    "benchmark_version": "0.1.0",
    "generated_at": "2025-06-25T12:00:00",
    "task": "image_retrieval",
    "datasets": {
      "thingseeg": {
        "n_subjects": 2,
        "n_samples": 100,
        "metrics": {"top1_accuracy": 0.632, "top5_accuracy": 0.891}
      },
      "nod": { ... }
    },
    "overall": {"top1_accuracy": 0.580, ...}
  }
"""

