def main():
    ap = argparse.ArgumentParser(
        description="EEG Benchmark Evaluation Script"
    )
    ap.add_argument("--h5_dir", type=str, required=True,
                    help="Directory containing .h5 files from the data loader")
    ap.add_argument("--task", type=str,
                    choices=list_tasks(),
                    default="image_retrieval",
                    help="Task to evaluate")
    ap.add_argument("--predictions", type=str, default=None,
                    help="JSON file mapping sample_id to model prediction")
    ap.add_argument("--output", type=str, default=None,
                    help="Save report JSON to this file")
    ap.add_argument("--metrics", type=str, nargs="+", default=None,
                    help="Specific metrics to compute (default: all applicable)")
    ap.add_argument("--info", action="store_true",
                    help="Just print dataset info, don't evaluate")
    args = ap.parse_args()

    if not os.path.isdir(args.h5_dir):
        log.error(f"Directory not found: {args.h5_dir}")
        sys.exit(1)

    # Discover h5 files
    h5_files = discover_h5_files(args.h5_dir, None if args.info else args.task)
    if not h5_files:
        log.error(f"No h5 files found in {args.h5_dir}")
        sys.exit(1)

    if args.info:
        print_dataset_info(args.h5_dir)
        return

    # Validate h5 schema against the task's declared schema (principle 4)
    schema = get_task_config(args.task).get("h5_schema")
    if schema:
        violations = []
        for info in h5_files:
            ok, errs = validate_h5_file(info["path"], schema)
            if not ok:
                violations.append(f"{info['filename']}: {'; '.join(errs)}")
        if violations:
            log.error(f"h5 schema validation failed for task '{args.task}':")
            for v in violations:
                log.error(f"  {v}")
            log.error("Fix the loader (schema is declared in TASK_REGISTRY).")
            sys.exit(1)

    # Load predictions
    if args.predictions is None:
        log.error("No predictions provided. Provide --predictions or use --info "
                   "to list available samples.")
        sys.exit(1)

    if not os.path.exists(args.predictions):
        log.error(f"Predictions file not found: {args.predictions}")
        sys.exit(1)

    with open(args.predictions, "r", encoding="utf-8") as fh:
        raw = json.load(fh)
    # 支持两种格式：直接 dict（旧）或
    # {candidate_pool_ids, candidate_embeddings?, predictions}（新）
    if isinstance(raw, dict) and "predictions" in raw:
        candidate_pool_ids = raw.get("candidate_pool_ids", [])
        candidate_embeddings = raw.get("candidate_embeddings", None)
        predictions = raw["predictions"]
    else:
        candidate_pool_ids = []
        candidate_embeddings = None
        predictions = raw
    log.info(f"Loaded {len(predictions)} predictions from {args.predictions}")

    # Extract ground truths from h5 files
    log.info(f"Extracting ground truths from {len(h5_files)} h5 files ...")
    ground_truths, sample_meta = extract_ground_truths(h5_files, args.task)
    log.info(f"Extracted {len(ground_truths)} ground-truth samples")

    # Generate report
    report = generate_report(
        task=args.task,
        ground_truths=ground_truths,
        predictions=predictions,
        h5_files=h5_files,
        metric_names=args.metrics,
        candidate_pool_ids=candidate_pool_ids,
        candidate_embeddings=candidate_embeddings,
        sample_meta=sample_meta,
    )

    # Print
    print_report(report)

    # Save
    if args.output:
        with open(args.output, "w", encoding="utf-8") as fh:
            json.dump(report, fh, indent=2, ensure_ascii=False)
        log.info(f"Report saved to {args.output}")


if __name__ == "__main__":
    main()
